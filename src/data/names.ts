export const NAMES_WITH_DIGITS = /ดีเซล\s?B(?:7|10|20)|แก๊สโซฮอล์\s?(?:9[15]|E10|E20|E85)|เบนซิน(?:ออกเทน)?\s?95|\bB(?:7|10|20)\b|\bE(?:10|20|85)\b|\bG95\b|\b10\s?PPM\b|\bPM\s?2\.5\b/g;
/** ตัวเลขอารบิกหรือเลขไทยที่เหลือหลังตัดชื่อเฉพาะออก */
export const hasLooseDigit = (s: string): boolean => /[0-9๐-๙]/.test(s.replace(NAMES_WITH_DIGITS, ''));
